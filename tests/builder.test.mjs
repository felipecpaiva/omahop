// Node check of Builder.js (the icon builder's pure logic):  node tests/builder.test.mjs
import { readFileSync } from "node:fs"
import assert from "node:assert/strict"
const B = new Function(readFileSync(new URL("../Builder.js", import.meta.url), "utf8").replace(".pragma library", "") +
  "; return { parseDraft, parseFind, suggestQuery, nowNames, nowPick, decorate, draftUrl, previewRows, gridMove, action, command, initial, begin, finish, refuse, packNames, parseSummary, parseExported, sizeText, defaultZipPath, LICENCES, DEFAULT_NAME }")()
const E = new Function(readFileSync(new URL("../PackEditor.js", import.meta.url), "utf8").replace(".pragma library", "") + "; return { appRows, iconStem }")()

// reading the scripts' output
assert.deepEqual(B.parseDraft("kitty\tkitty.svg\t/c/draft/icons/kitty.svg\nbad\tbad.png\trelative\n\nlone\n"), [{ stem: "kitty", file: "kitty.svg", path: "/c/draft/icons/kitty.svg" }])
assert.deepEqual(B.parseFind("Papirus\tfirefox\t/u/Papirus/firefox.svg\nYaru\tfire\tnot-absolute\nYaru\tfire\t/u/Yaru/fire.png\n"),
  [{ theme: "Papirus", name: "firefox", path: "/u/Papirus/firefox.svg" }, { theme: "Yaru", name: "fire", path: "/u/Yaru/fire.png" }])
assert.deepEqual(B.parseFind(""), [])

// the first search text
assert.equal(B.suggestQuery("firefox", "firefox-esr"), "firefox-esr", "the entry's icon name first")
assert.equal(B.suggestQuery("org.gnome.Nautilus", ""), "nautilus", "last part of a dotted id")
assert.equal(B.suggestQuery("Steam App 1", "/abs/icon.png"), "steam-app-1", "a path is not a name")
assert.equal(B.suggestQuery("a$(x);b", ""), "axb", "nothing a shell would read")

// the "Now" icon
assert.deepEqual(B.nowNames(["firefox", "/abs/x.png", "a b", "Fire.Fox"]), ["firefox", "Fire.Fox"])
assert.equal(B.nowPick(["a", "b"], { b: "/t/b.svg" }), "/t/b.svg")
assert.equal(B.nowPick(["a"], {}), "")

// rows: the editor's app rows fed the draft's files, plus the changed flag
const pick = (key) => (key === "kitty" ? "/c/draft/icons/kitty.svg" : "")
const rows = B.decorate(E.appRows([{ appId: "kitty", name: "Kitty", icon: "kitty" }], [{ id: "firefox", name: "Firefox", icon: "firefox" }, { id: "zed", name: "Zed", icon: "zed" }], ["/c/draft/icons/kitty.svg", "/c/draft/icons/orphan.png"], pick, ""))
assert.deepEqual(rows.map((r) => [r.key, r.running, r.changed]), [["kitty", true, true], ["firefox", false, false], ["zed", false, false], ["orphan", false, true]],
  "open first, then installed by name, then draft icons no app uses")
const filtered = B.decorate(E.appRows([], [{ id: "firefox", name: "Firefox", icon: "" }, { id: "zed", name: "Zed", icon: "" }], [], () => "", "  FIRE "))
assert.deepEqual(filtered.map((r) => r.key), ["firefox"], "the filter works on name and id, any case")
assert.equal(B.draftUrl(rows[0], 3), "file:///c/draft/icons/kitty.svg?v=3")
assert.equal(B.draftUrl(rows[1], 3), "", "an unchanged app has no draft url")
assert.deepEqual(B.previewRows(rows, 3, 3).map((r) => r.key), ["orphan", "kitty", "firefox"], "wraps")
assert.deepEqual(B.previewRows([], 0, 3), [])
assert.equal(B.previewRows(rows, 0, 9).length, rows.length)

// grid movement (4 columns, 10 cells)
assert.equal(B.gridMove(0, "Right", 10, 4), 1)
assert.equal(B.gridMove(9, "Right", 10, 4), 9)
assert.equal(B.gridMove(1, "Up", 10, 4), 1, "top row stays")
assert.equal(B.gridMove(5, "Up", 10, 4), 1)
assert.equal(B.gridMove(7, "Down", 10, 4), 9, "a short last row clamps")
assert.equal(B.gridMove(0, "Left", 10, 4), 0)
assert.equal(B.gridMove(0, "Home", 10, 4), -1, "not a grid key")
assert.equal(B.gridMove(0, "Down", 0, 4), -1, "empty grid")

// keys
const S = (zone, baseOpen = false) => ({ zone, baseOpen })
assert.deepEqual(B.action("Escape", false, S("apps")), { act: "back" })
assert.deepEqual(B.action("Escape", false, S("icons", true)), { act: "closeBase" })
assert.deepEqual(B.action("z", true, S("apps")), { act: "undo" })
assert.deepEqual(B.action("z", false, S("apps")), { act: "none" }, "typing z is typing")
assert.deepEqual(B.action("r", true, S("icons")), { act: "resetApp" })
assert.deepEqual(B.action("Tab", false, S("apps")), { act: "zone" })
assert.deepEqual(B.action("Down", false, S("apps")), { act: "appMove", key: "Down" })
assert.deepEqual(B.action("Down", false, S("icons")), { act: "gridMove", key: "Down" })
assert.deepEqual(B.action("Down", false, S("icons", true)), { act: "baseMove", key: "Down" })
assert.deepEqual(B.action("Return", false, S("apps")), { act: "zone" })
assert.deepEqual(B.action("Return", false, S("icons")), { act: "apply" })
assert.deepEqual(B.action("Return", false, S("apps", true)), { act: "baseChoose" })
assert.deepEqual(B.action("Left", false, S("apps")), { act: "none" }, "left and right edit the text in the app filter")

// commands are argument arrays; a hostile value is refused before anything runs
const tools = { draft: "/t/draft-edit.sh", find: "/t/icon-find.sh", preview: "/t/icon-preview.sh", pick: "/t/pack-edit.sh" }
assert.deepEqual(B.command(tools, "add", { appId: "kitty", path: "/x/a.png" }).argv, ["bash", "/t/draft-edit.sh", "add", "kitty", "/x/a.png"])
assert.deepEqual(B.command(tools, "reset", { appId: "kitty" }).argv, ["bash", "/t/draft-edit.sh", "reset-app", "kitty"])
assert.deepEqual(B.command(tools, "pick", {}).argv, ["bash", "/t/pack-edit.sh", "pick", "image"])
assert.deepEqual(B.command(tools, "find", { query: "fox" }).argv, ["bash", "/t/icon-find.sh", "fox", "120"])
assert.deepEqual(B.command(tools, "now", { theme: "", names: ["a", "b c"] }).argv, ["bash", "/t/icon-preview.sh", "-", "a"], "no theme is a dash; a bad name is dropped")
for (const bad of [{ appId: "", path: "/x" }, { appId: "k", path: "rel.png" }, { appId: "k\nx", path: "/x" }, { appId: "k", path: "/x\ny" }, { appId: "k\0", path: "/x" }])
  assert.ok(B.command(tools, "add", bad).error, JSON.stringify(bad))
assert.ok(B.command(tools, "find", { query: "a" }).error, "one letter is too short")
assert.ok(B.command(tools, "nope", {}).error)

// the state machine
let st = B.initial()
st = B.begin(st, "add")
assert.equal(st.phase, "busy")
assert.equal(B.begin(st, "undo"), st, "one action at a time")
assert.equal(B.refuse(st, "x"), st, "a refusal does not interrupt a running action")
let done = B.finish(st, "add", 0, "kitty.svg\n", "", { appId: "kitty" })
assert.deepEqual([done.phase, done.error, done.effect], ["idle", false, { refresh: true }])
done = B.finish(B.begin(B.initial(), "add"), "add", 1, "", "omahop draft edit: not added, the image must be a PNG or a plain SVG:\nline 2\n", {})
assert.equal(done.error, true)
assert.match(done.message, /^not added, the image must be a PNG or a plain SVG: line 2$/, "the script's prefix is dropped")
assert.equal(B.finish(B.begin(B.initial(), "undo"), "undo", 1, "", "", {}).message, "Failed (exit 1)")
let pickDone = B.finish(B.begin(B.initial(), "pick"), "pick", 0, "/pics/a.png\n", "", { appId: "kitty" })
assert.deepEqual(pickDone.effect, { run: "add", args: { appId: "kitty", path: "/pics/a.png" } }, "a picked file goes to add for the app chosen at the time")
pickDone = B.finish(B.begin(B.initial(), "pick"), "pick", 1, "", "", {})
assert.deepEqual([pickDone.error, pickDone.message, pickDone.manualPath], [false, "", false], "nothing picked is not an error")
pickDone = B.finish(B.begin(B.initial(), "pick"), "pick", 2, "", "no chooser", {})
assert.deepEqual([pickDone.error, pickDone.manualPath], [true, true], "a chooser that did not open offers a typed path")
assert.equal(B.finish(B.begin(pickDone, "add"), "add", 0, "a.png", "", {}).manualPath, false, "a successful add clears it")
// save, open-pack, discard
const sv = { name: " my icons ", author: "Nova", licence: "MIT", description: "", basedOn: "" }
assert.deepEqual(B.command(tools, "save", sv).argv, ["bash", "/t/draft-edit.sh", "save", "my icons", "Nova", "MIT"], "trimmed, no empty description")
assert.deepEqual(B.command(tools, "save", Object.assign({}, sv, { replace: true, basedOn: "Papirus", description: "d", author: "" })).argv,
  ["bash", "/t/draft-edit.sh", "save", "--replace", "--based-on", "Papirus", "my icons", "", "MIT", "d"], "an empty author stays an argument")
for (const bad of [{ name: "  " }, { name: "a\nb" }, { licence: "" }, { description: "x\ny" }, { author: "a\0" }]) assert.ok(B.command(tools, "save", Object.assign({}, sv, bad)).error, JSON.stringify(bad))
assert.deepEqual(B.command(tools, "openPack", { name: "mine", force: true }).argv, ["bash", "/t/draft-edit.sh", "open-pack", "--force", "mine"])
assert.deepEqual(B.command(tools, "openPack", { name: "mine" }).argv, ["bash", "/t/draft-edit.sh", "open-pack", "mine"])
for (const name of ["", "../x", "a b", "--force"]) assert.ok(name === "--force" ? B.command(tools, "openPack", { name }).argv : B.command(tools, "openPack", { name }).error, name)
assert.deepEqual(B.command(tools, "discard", {}).argv, ["bash", "/t/draft-edit.sh", "discard"])
assert.deepEqual(B.packNames("a\n\n../x\nb-1\n"), ["a", "b-1"])
assert.ok(B.LICENCES.includes("CC0-1.0") && B.DEFAULT_NAME === "my-icons")
let sd = B.finish(B.begin(B.initial(), "save"), "save", 0, "my-icons\n", "", {})
assert.deepEqual([sd.error, sd.effect], [false, { refresh: true, saved: "my-icons" }])
sd = B.finish(B.begin(B.initial(), "save"), "save", 1, "", "omahop draft edit: a pack named my-icons already exists (use Replace)\n", {})
assert.deepEqual([sd.error, sd.message, sd.effect], [false, "", { clash: true }], "a clash is a question, not an error")
sd = B.finish(B.begin(B.initial(), "save"), "save", 1, "", "omahop draft edit: not saved, the draft is untouched:\nskipped icons/x.svg\n", {})
assert.equal(sd.error, true)
assert.deepEqual(B.finish(B.begin(B.initial(), "openPack"), "openPack", 1, "", "omahop draft edit: the draft has changes; discard it first or use --force", {}).effect, { needForce: true })
assert.equal(B.finish(B.begin(B.initial(), "openPack"), "openPack", 1, "", "omahop draft edit: no pack folder named x", {}).error, true)
assert.deepEqual(B.finish(B.begin(B.initial(), "openPack"), "openPack", 0, "Opened a with 3 icons\n", "", {}).effect, { refresh: true })
assert.deepEqual(B.finish(B.begin(B.initial(), "discard"), "discard", 0, "Discarded the draft\n", "", {}).effect, { refresh: true })
// export and import (slice 3)
const tools3 = { draft: "/t/draft-edit.sh", pick: "/t/pack-edit.sh", export: "/t/pack-export.sh", import: "/t/pack-import.sh" }
assert.deepEqual(B.command(tools3, "export", { name: "mine", out: "/d/mine.zip" }).argv, ["bash", "/t/pack-export.sh", "mine", "/d/mine.zip"])
assert.deepEqual(B.command(tools3, "export", { name: "mine", out: "/d/mine.zip", force: true }).argv, ["bash", "/t/pack-export.sh", "mine", "/d/mine.zip", "--force"])
for (const bad of [{ name: "../x", out: "/d/a.zip" }, { name: "", out: "/d/a.zip" }, { name: "m", out: "rel.zip" }, { name: "m", out: "/d/a.png" }, { name: "m", out: "/d/a\n.zip" }, { name: "--force", out: "relative" }])
  assert.ok(B.command(tools3, "export", bad).error || bad.name === "--force", JSON.stringify(bad))
assert.deepEqual(B.command(tools3, "importCheck", { zip: "/z/a.zip" }).argv, ["bash", "/t/pack-import.sh", "/z/a.zip", "--dry-run"])
assert.deepEqual(B.command(tools3, "importDo", { zip: "/z/a.zip", replace: true }).argv, ["bash", "/t/pack-import.sh", "/z/a.zip", "--yes", "--replace"])
assert.deepEqual(B.command(tools3, "importDo", { zip: "/z/a.zip" }).argv, ["bash", "/t/pack-import.sh", "/z/a.zip", "--yes"])
assert.deepEqual(B.command(tools3, "openZip", { zip: "/z/a.zip", force: true }).argv, ["bash", "/t/draft-edit.sh", "open-zip", "--force", "/z/a.zip"])
for (const op of ["importCheck", "importDo", "openZip"]) for (const zip of ["", "a.zip", "/a\nb.zip", "-x"]) assert.ok(B.command(tools3, op, { zip }).error, op + " " + zip)
assert.deepEqual(B.command(tools3, "pickDir", {}).argv, ["bash", "/t/pack-edit.sh", "pick", "dir"])
assert.deepEqual(B.command(tools3, "pickZip", {}).argv, ["bash", "/t/pack-edit.sh", "pick", "zip"])
assert.deepEqual(B.command(tools3, "exportDir", {}).argv, ["bash", "/t/pack-edit.sh", "export-dir"])
const dry = "Pack:     omahop sample\nAuthor:   Nova\nLicense:  CC0-1.0\nIcons:    3\nInstall:  /h/.config/omahop/packs/omahop-sample (a pack of this name is installed; --replace replaces it)\nInstalled already: yes\nFiles:\n  pack.toml\n  icons/a.png\n"
assert.deepEqual(B.parseSummary(dry), { name: "omahop sample", author: "Nova", licence: "CC0-1.0", icons: 3, folder: "omahop-sample", installed: true, files: ["pack.toml", "icons/a.png"] })
assert.equal(B.parseSummary("Installed already: no\n"), null)
assert.equal(B.parseSummary(dry.replace("Installed already: yes", "Installed already: no")).installed, false)
assert.deepEqual(B.parseExported("Exported mine (2 icons, 1124 bytes) to /d/my zip.zip\nLeft out of pack.toml: notes\n"), { name: "mine", icons: 2, bytes: 1124, path: "/d/my zip.zip" })
assert.equal(B.parseExported("nope"), null)
assert.deepEqual([B.sizeText(0), B.sizeText(900), B.sizeText(1536), B.sizeText(5 * 1048576)], ["0 B", "900 B", "1.5 KB", "5.0 MB"])
assert.equal(B.defaultZipPath("/h/Downloads/", "mine"), "/h/Downloads/mine.zip")
let ex = B.finish(B.begin(B.initial(), "export"), "export", 0, "Exported mine (2 icons, 1536 bytes) to /d/mine.zip\n", "", {})
assert.deepEqual([ex.error, ex.message, ex.effect.exported.path], [false, "Exported mine (2 icons, 1.5 KB) to /d/mine.zip", "/d/mine.zip"], "the result shows path and size")
ex = B.finish(B.begin(B.initial(), "export"), "export", 1, "", "omahop pack export: /d/mine.zip exists, add --force to replace it", {})
assert.deepEqual([ex.error, ex.effect], [false, { overwrite: true }], "an existing file is a question")
ex = B.finish(B.begin(B.initial(), "export"), "export", 1, "", "omahop pack export: not exported, pack.toml description names a place on this computer: x (change it and export again)", {})
assert.equal(ex.error, true)
assert.match(ex.message, /^not exported, pack.toml description names a place/, "the refusal reason is shown")
assert.deepEqual(B.finish(B.begin(B.initial(), "pickDir"), "pickDir", 0, "/h/Downloads\n", "", {}).effect, { dir: "/h/Downloads" })
assert.equal(B.begin(B.initial(), "pickDir").message, "", "no Working... while the chooser is open")
assert.equal(B.finish(B.begin(B.initial(), "pickDir"), "pickDir", 1, "", "", {}).error, false)
assert.deepEqual(B.finish(B.begin(B.initial(), "pickDir"), "pickDir", 2, "", "x", {}).manualPath, true)
assert.deepEqual(B.finish(B.begin(B.initial(), "pickZip"), "pickZip", 0, "/z/a.zip\n", "", {}).effect, { run: "importCheck", args: { zip: "/z/a.zip" } }, "a chosen zip goes to the dry run")
assert.equal(B.finish(B.begin(B.initial(), "importCheck"), "importCheck", 0, dry, "", {}).effect.summary.icons, 3)
const refused = B.finish(B.begin(B.initial(), "importCheck"), "importCheck", 1, "", "omahop pack import: refused, the zip holds icons/x.png: a path that leads out of the pack\n", {})
assert.deepEqual([refused.error, refused.message], [true, "refused, the zip holds icons/x.png: a path that leads out of the pack"], "an import refusal is shown whole")
assert.equal(B.finish(B.begin(B.initial(), "importCheck"), "importCheck", 0, "junk", "", {}).error, true)
assert.deepEqual(B.finish(B.begin(B.initial(), "importDo"), "importDo", 0, "Installed.\n", "", { folder: "omahop-sample", name: "omahop sample" }).effect, { installed: "omahop-sample" })
assert.deepEqual(B.finish(B.begin(B.initial(), "openZip"), "openZip", 0, "Opened the zip with 3 icons\n", "", {}).effect, { refresh: true, opened: true })
assert.deepEqual(B.finish(B.begin(B.initial(), "openZip"), "openZip", 1, "", "omahop draft edit: the draft has changes; discard it first or use --force", {}).effect, { needForce: true })
console.log("ok   builder logic: parsers, rows, preview, grid, keys, commands, state machine")
