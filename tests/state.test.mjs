// Node check of State.js:  node tests/state.test.mjs
import { readFileSync } from "node:fs"
import assert from "node:assert/strict"
const src = readFileSync(new URL("../State.js", import.meta.url), "utf8").replace(".pragma library", "")
const State = new Function(src + "; return { thumbnailExcludeSet, isThumbnailExcluded, parse, visibleRows, borderWidth, normalizeAddress, visibleCards, listHeight, tabCaption, tabIcon, tabPicture, tabPictureKind }")()

const text = "version=1\nopen=1\nrevealed=1\nselected=2\nstyle=list\nthumbnails=snapshot\nw\t0xa\tkitty\t0\t1\tfirst title\nw\t0xb\tgoogle-chrome\t1\t\tsecond\ttitle with a tab\n"
const s = State.parse(text)
assert.equal(s.open, true); assert.equal(s.revealed, true); assert.equal(s.selected, 2); assert.equal(s.style, "list")
assert.equal(s.entries.length, 2)
assert.deepEqual(s.entries[0], { address: "0xa", appId: "kitty", minimized: false, hint: "1", title: "first title" })
assert.equal(s.entries[1].hint, "", "an empty hint field means no hint")
assert.equal(s.entries[1].minimized, true); assert.equal(s.entries[1].title, "second\ttitle with a tab")

// closed or garbage input never throws and shows nothing
assert.equal(State.parse("").open, false)
assert.equal(State.parse(null).open, false)
assert.equal(State.parse("open=1\nrevealed=1\nselected=5\nw\t0xa\tk\t0\t\tt\n").open, false, "selection outside the list: not shown")
assert.equal(State.parse("open=1\nselected=0\n").open, false)
assert.equal(State.parse("junk line\n=\nopen\n").entries.length, 0)
assert.equal(State.parse("open=0\nrevealed=0\nselected=1\nw\t0xa\tk\t0\t\tt\n").open, false)

// visible rows: bounded by the cap and by the screen
assert.equal(State.visibleRows(1080, 48, 9), 9)
assert.equal(State.visibleRows(600, 48, 9), 8)
assert.equal(State.visibleRows(100, 48, 9), 1)
// border: auto follows Hyprland (0 = no outline), on/off override it
assert.equal(State.borderWidth("auto", 0, 2), 0, "auto with window borders off: none")
assert.equal(State.borderWidth("auto", 3, 2), 3, "auto follows a 3 px border")
assert.equal(State.borderWidth("auto", -1, 2), 2, "auto while Hyprland's value is unknown: the fallback")
assert.equal(State.borderWidth("on", 0, 2), 2, "on forces an outline even when Hyprland has none")
assert.equal(State.borderWidth("on", 4, 2), 4)
assert.equal(State.borderWidth("off", 4, 2), 0, "off removes it")
assert.equal(State.parse("border=off\nopen=0\n").border, "off"); assert.equal(State.parse("").border, "auto")
assert.equal(State.normalizeAddress("0x55CB5923D480"), "55cb5923d480"); assert.equal(State.normalizeAddress("55cb5923d480"), "55cb5923d480"); assert.equal(State.normalizeAddress(null), "")
assert.equal(State.visibleCards(1280, 240, 12, 6), 4, "four 240 px cards fit in 90% of 1280 (five need 1248 of 1152 px)")
assert.equal(State.visibleCards(3000, 240, 12, 6), 6, "capped")
assert.equal(State.visibleCards(200, 240, 12, 6), 1, "at least one")
// search: the query is read; a search with no match stays open with an empty list; a bad selection without a query still hides everything
assert.equal(State.parse("open=1\nrevealed=1\nselected=1\nquery=chr\nw\t0xa\tk\t0\t\tt\n").query, "chr")
const none = State.parse("open=1\nrevealed=1\nselected=0\nquery=zzz\n")
assert.equal(none.open, true); assert.equal(none.entries.length, 0)
assert.equal(State.parse("open=1\nrevealed=1\nselected=0\n").open, false, "no query and nothing selected: hidden")
assert.equal(State.parse("").query, "")
assert.equal(State.parse("actions=1\n").actions, true); assert.equal(State.parse("actions=0\n").actions, false); assert.equal(State.parse("").actions, true, "buttons on by default")
// thumbnail exclusions: whole classes, case-insensitive, spaces around commas ignored
const ex = State.thumbnailExcludeSet(" Kitty ,1Password,, org.gnome.Nautilus , my-app ")
assert.equal(State.isThumbnailExcluded(ex, "kitty"), true)
assert.equal(State.isThumbnailExcluded(ex, "KITTY"), true)
assert.equal(State.isThumbnailExcluded(ex, "1password"), true)
assert.equal(State.isThumbnailExcluded(ex, "org.gnome.Nautilus"), true, "dots")
assert.equal(State.isThumbnailExcluded(ex, "my-app"), true, "dashes")
assert.equal(State.isThumbnailExcluded(ex, "kitty-terminal"), false, "a class that contains an excluded word is not a match")
assert.equal(State.isThumbnailExcluded(ex, "org.gnome"), false)
assert.equal(State.isThumbnailExcluded(ex, "my"), false)
assert.equal(State.isThumbnailExcluded(State.thumbnailExcludeSet(""), "kitty"), false, "empty list excludes nothing")
assert.equal(State.isThumbnailExcluded(State.thumbnailExcludeSet(undefined), ""), false)
assert.equal(State.isThumbnailExcluded(ex, ""), false, "no class is never excluded")
assert.equal(State.isThumbnailExcluded(ex, "constructor"), false, "inherited object keys are not classes")
console.log("state ok")

// v1.1b linger: seq, grab and the countdown; a closed session never grabs
const lg = State.parse("open=1\nrevealed=1\nselected=1\nseq=7\ngrab=1\nlinger_ms=3000\nlinger_rev=4\nquery=br\nw\t0xa\tk\t0\t\tbravo\n")
assert.equal(lg.seq, 7); assert.equal(lg.grab, true); assert.equal(lg.lingerMs, 3000); assert.equal(lg.lingerRev, 4)
const plain = State.parse(text)
assert.equal(plain.grab, false); assert.equal(plain.lingerMs, 0); assert.equal(plain.seq, 0)
assert.equal(State.parse("open=0\nseq=9\ngrab=1\nlinger_ms=3000\n").grab, false, "open=0 drops the grab")
assert.equal(State.parse("open=0\nseq=9\n").seq, 9, "seq is read when closed too (a restarted shell continues from it)")
assert.equal(State.parse("open=1\nrevealed=1\nselected=5\ngrab=1\nw\t0xa\tk\t0\t\tt\n").grab, false, "a stale file never grabs")
console.log("state linger ok")

// browser tab rows (v1.4): parsed with their site and active flag, counted in the selection, sized as compact rows
{
  const st = State.parse("open=1\nrevealed=1\nselected=2\nquery=notes\nw\t0xa\tchromium\t0\t\tAlpha - Chromium\nt\t0xa\tchromium\t0\t1\t0123456789abcdef\t0123456789abcdef/fedcba9876543210-17\t1\tnotes.example.com\tTeam = notes\tpart two\nt\t0xa\tchromium\t1\t0\t\t\t0\t\t\n")
  assert.equal(st.open, true, "a tab row can be the selected one")
  assert.equal(st.entries.length, 3)
  assert.deepEqual(st.entries[1], { address: "0xa", appId: "chromium", minimized: false, hint: "", tab: true, active: true, icon: "0123456789abcdef", picture: "0123456789abcdef/fedcba9876543210-17", asleep: true, host: "notes.example.com", title: "Team = notes\tpart two" })
  assert.equal(st.query, "notes", "a title with = is never read as a key")
  assert.equal(st.entries[2].asleep, false); assert.equal(st.entries[2].host, ""); assert.equal(st.entries[2].title, ""); assert.equal(st.entries[2].minimized, true)
  assert.equal(State.parse("open=1\nrevealed=1\nselected=1\nt\t0xa\tc\t0\t1\tnotes\ttitle\n").entries.length, 0, "a short tab line is dropped (the older format without an icon field)")
  assert.equal(State.parse("open=1\nrevealed=1\nselected=1\nt\t0xa\tc\t0\t1\t0123456789abcdef\tnotes\ttitle\n").entries.length, 0, "a tab line of the format before page pictures is dropped")
  assert.equal(State.parse("open=1\nrevealed=1\nselected=1\nt\t0xa\tc\t0\t1\t0123456789abcdef\t0123456789abcdef/fedcba9876543210-17\tnotes\ttitle\n").entries.length, 0, "a tab line of the format before the asleep field is dropped")
  assert.equal(State.listHeight(st.entries, 46, 30, 9), 46 + 30 + 30)
  assert.equal(State.listHeight(st.entries, 46, 30, 2), 46 + 30, "only maxRows rows count")
  assert.equal(State.listHeight([], 46, 30, 9), 0)
  assert.equal(State.tabCaption(st.entries[1], "shown"), "notes.example.com  ·  shown")
  assert.equal(State.tabCaption({ host: "a.example", active: false }, "shown"), "a.example")
  assert.equal(State.tabCaption({ host: "", active: true }, "shown"), "shown")
  assert.equal(State.tabCaption(null, "shown"), "")
  assert.equal(State.tabIcon(st.entries[1], "/run/user/1/omahop/tabicons", "fallback"), "file:///run/user/1/omahop/tabicons/0123456789abcdef.png")
  assert.equal(State.tabIcon(st.entries[2], "/d", "fallback"), "fallback", "no icon: the browser's own icon")
  for (const bad of ["../../etc/passwd", "0123456789ABCDEF", "0123456789abcde", "0123456789abcdef0", "a/b"]) assert.equal(State.tabIcon({ icon: bad }, "/d", "fb"), "fb", "a key that is not 16 hex digits is never a path: " + bad)
  assert.equal(State.tabIcon(st.entries[1], "", "fb"), "fb")
  assert.equal(State.tabPicture(st.entries[1], "/run/user/1/omahop/tabpics"), "file:///run/user/1/omahop/tabpics/0123456789abcdef/fedcba9876543210-17.jpg")
  assert.equal(State.tabPicture(st.entries[2], "/d"), "", "no picture: empty")
  for (const bad of ["../../etc/passwd", "4242-17-3", "0123456789abcdef/fedcba9876543210", "0123456789abcdef/fedcba9876543210-", "0123456789abcdef/fedcba9876543210-17.jpg", "0123456789abcde/fedcba9876543210-17", "0123456789ABCDEF/fedcba9876543210-17", "0123456789abcdef/fedcba9876543210-" + "9".repeat(13), "../0123456789abcdef/fedcba9876543210-17", "0123456789abcdef//fedcba9876543210-17", ""]) assert.equal(State.tabPicture({ picture: bad }, "/d"), "", "a name that is not <hosthash>/<urlkey>-<n> is never a path: " + bad)
  assert.equal(State.tabPicture({ picture: "0123456789abcdef/fedcba9876543210-17d" }, "/d"), "file:///d/0123456789abcdef/fedcba9876543210-17d.jpg", "a drawn picture is a path too")
  for (const bad of ["0123456789abcdef/fedcba9876543210-17dd", "0123456789abcdef/fedcba9876543210-17D", "0123456789abcdef/fedcba9876543210-d", "0123456789abcdef/fedcba9876543210-17d/x", "0123456789abcdef/fedcba9876543210-17d.jpg", "../0123456789abcdef/fedcba9876543210-17d", "0123456789abcdef/fedcba9876543210-" + "9".repeat(12) + "dd", "0123456789abcdef/fedcba9876543210-" + "9".repeat(13) + "d"]) {
    assert.equal(State.tabPicture({ picture: bad }, "/d"), "", "not a picture name: " + bad)
    assert.equal(State.tabPictureKind({ picture: bad }), "", "no kind for: " + bad)
  }
  assert.equal(State.tabPictureKind({ picture: "0123456789abcdef/fedcba9876543210-17d" }), "drawn")
  assert.equal(State.tabPictureKind({ picture: "0123456789abcdef/fedcba9876543210-17" }), "shot")
  assert.equal(State.tabPictureKind({}), "")
  assert.equal(State.tabPictureKind(null), "")
  assert.equal(State.tabPicture(st.entries[1], ""), "")
  assert.equal(State.tabPicture(null, "/d"), "")
  console.log("state tabs ok")
}
