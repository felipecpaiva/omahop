// node validate.test.js <scratch-dir>   (builds the fixture zips into <scratch-dir> with python, then checks them with real `unzip -Zl`)
const assert = require("node:assert/strict")
const { execFileSync } = require("node:child_process")
const fs = require("node:fs")
const V = require("./PackValidate.js")
const dir = process.argv[2]
execFileSync("python3", ["-I", __dirname + "/make_zips.py", dir])
const list = (n) => {
  const p = dir + "/" + n
  return V.validateListing(V.parseListing(execFileSync("unzip", ["-Zl", p]).toString()), fs.statSync(p).size)
}
const bad = (n, re) => {
  const r = list(n)
  assert.equal(r.ok, false, n + " must be rejected")
  assert.ok(r.errors.some((e) => re.test(e)), n + ": " + r.errors.slice(0, 3))
}
assert.equal(list("good.zip").ok, true, "good: " + list("good.zip").errors)
bad("traversal.zip", /dot segment/)
bad("absolute.zip", /absolute/)
bad("backslash.zip", /backslash/)
bad("hidden.zip", /hidden/)
bad("symlink.zip", /not a regular file/)
bad("script.zip", /not an allowed file/)
bad("nested.zip", /not an allowed file|folder/)
bad("dupcase.zip", /duplicate/)
bad("nomanifest.zip", /pack.toml missing/)
bad("bomb.zip", /ratio/)
bad("manyfiles.zip", /too many/)
// the same checks through bsdtar's listing (what the product would use)
const blist = (n) => { const p = dir + "/" + n; return V.validateListing(V.parseBsdtar(execFileSync("bsdtar", ["-tvf", p]).toString()), fs.statSync(p).size) }
assert.equal(blist("good.zip").ok, true)
assert.equal(blist("symlink.zip").ok, false, "symlink rejected via bsdtar listing")
assert.ok(blist("symlink.zip").errors.some((e) => /not a regular file/.test(e)))
assert.equal(blist("script.zip").ok, false)
assert.equal(blist("dupcase.zip").ok, false)
assert.equal(blist("manyfiles.zip").ok, false)
assert.equal(blist("traversal.zip").ok, false, "bsdtar prints the name; our path rule rejects it")
assert.equal(V.parseBsdtar("-rw-r--r--  0 1000   1000        6 Nov  7 13:19 icons/my app.svg")[0].name, "icons/my app.svg")
// bytes
const read = (z, f) => new Uint8Array(execFileSync("unzip", ["-p", dir + "/" + z, f], { maxBuffer: 1 << 26 }))
assert.equal(V.validateBytes("a.png", read("good.zip", "icons/firefox.png")), "")
assert.equal(V.validateBytes("a.png", read("bigpng.zip", "icons/huge.png")), "PNG dimensions too large")
assert.equal(V.validateBytes("a.png", new TextEncoder().encode("GIF89a not a png at all, padding padding padding")), "not a PNG")
assert.equal(V.validateBytes("a.svg", read("good.zip", "icons/kitty.svg")), "")
const svg = (s) => V.validateBytes("a.svg", new TextEncoder().encode(s))
assert.match(svg("<svg><script>alert(1)</script></svg>"), /active/)
assert.match(svg('<svg><image href="file:///etc/passwd"/></svg>'), /external/)
assert.match(svg('<svg><image xlink:href="https://x.test/a.png"/></svg>'), /external/)
assert.match(svg('<svg onload="x()"/>'), /event/)
assert.match(svg('<!DOCTYPE svg [<!ENTITY a "b">]><svg/>'), /entity/)
assert.match(svg('<svg><rect fill="url(http://x/y)"/></svg>'), /url\(\)/)
assert.equal(svg('<svg><use href="#a"/><rect fill="url(#g)"/></svg>'), "", "in-document refs are fine")
assert.equal(svg('<?xml version="1.0"?>\n<!-- c -->\n<svg viewBox="0 0 1 1"/>'), "")
assert.match(svg("<html></html>"), /not an SVG/)
// manifest
assert.deepEqual(V.validateManifest({ schema: 1, id: "demo", name: "Demo" }), [])
assert.equal(V.validateManifest({ schema: 2, id: "../x", name: "" }).length, 3)
// path helper
for (const p of ["a/../b", "/a", "C:/a", "a\\b", "a//b", ".hidden", "a\nb", "~/x"]) assert.notEqual(V.badPath(p), "", p)
assert.equal(V.badPath("icons/ok-name.png"), "")
console.log("validate ok")
